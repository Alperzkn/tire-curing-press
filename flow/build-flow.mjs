// Builds the Flow Creator (Node-RED) flow that runs the press simulation on Industrial Edge.
// The function node embeds sim/press-model.js verbatim, so edit the model and rebuild; never edit the node.
// node flow/build-flow.mjs [--connector tirepress1] [--connection factory] [--publish-ms 500] [--out flow/tire-press-flow.json]
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MODEL = join(ROOT, "sim/press-model.js");
const arg = (name, fallback) => { const i = process.argv.indexOf(`--${name}`); return i > 0 ? process.argv[i + 1] : fallback; };
const options = {
  connector: arg("connector", "tirepress1"),
  connection: arg("connection", "factory"),
  publishEveryMs: Number(arg("publish-ms", 500)),
};
const out = arg("out", join(ROOT, "flow/tire-press-flow.json"));
if (!/^[A-Za-z0-9_-]+$/.test(options.connector) || !/^[A-Za-z0-9_-]+$/.test(options.connection)) throw new Error("connector and connection may only use letters, digits, _ and -");
if (!(options.publishEveryMs >= 100)) throw new Error("--publish-ms must be at least 100");

const M = createRequire(import.meta.url)(MODEL);
M.configure(options);
const T = M.topics();
const source = readFileSync(MODEL, "utf8");
const published = M.publishedChunks;
const echoed = M.chunks.filter((chunk) => chunk.external).map((chunk) => chunk.name);
const NS = M.CONFIG.namespace;

// stable node IDs, so importing a rebuilt flow replaces the old nodes instead of duplicating them
const id = (key) => {
  let a = 2166136261, b = 5381;
  for (const ch of `tire-press:${key}`) { a = Math.imul(a ^ ch.charCodeAt(0), 16777619); b = Math.imul(b, 33) ^ ch.charCodeAt(0); }
  return ((a >>> 0).toString(16).padStart(8, "0") + (b >>> 0).toString(16).padStart(8, "0")).slice(0, 16);
};
const TAB = id("tab"), BROKER = id("broker"), MAIN = id("main"), MAP = id("map-write");

const main = `// Generated by flow/build-flow.mjs from sim/press-model.js ${M.VERSION}. Edit the model and rebuild; do not edit here.
const TirePress = (() => {
const module = { exports: {} };
const exports = module.exports;
${source}
return module.exports;
})();
TirePress.configure(${JSON.stringify(options)});
const PUBLISHED = ${JSON.stringify(published)};
const ECHOED = ${JSON.stringify(echoed)};
const out = () => new Array(1 + PUBLISHED.length + ECHOED.length).fill(null);
const metadataMessage = () => ({ payload: TirePress.metadata() });
if (msg.topic === "tcp/metadata") { const o = out(); o[0] = metadataMessage(); return o; }
const now = Date.now();
let state = flow.get("tcpState");
let fresh = false;
if (!state || state.version !== TirePress.VERSION) {
    if (state) node.warn("Model version changed from " + state.version + " to " + TirePress.VERSION + ": simulation state reset");
    state = TirePress.createState(now);
    fresh = true;
}
try {
    TirePress.advance(state, now);
    if (msg.topic === "tcp/write" || msg.topic === "tcp/command") {
        const values = msg.topic === "tcp/write" ? TirePress.parseWrite(msg.payload) : msg.payload;
        const result = TirePress.applyWrites(state, values, now);
        flow.set("tcpState", state);
        if (result.errors.length) node.warn("Write refused: " + result.errors.join("; "));
        node.status({ fill: result.errors.length ? "yellow" : "blue", shape: "dot", text: ("write " + (result.applied.join(", ") || "refused")).slice(0, 80) });
        const o = out();
        for (const echo of result.echoes) {
            const index = ECHOED.indexOf(echo.chunk);
            if (index >= 0) o[1 + PUBLISHED.length + index] = { payload: echo.payload };
        }
        return o;
    }
    const messages = TirePress.messages(state);
    flow.set("tcpState", state);
    const o = out();
    if (fresh) o[0] = metadataMessage();
    for (const message of messages) o[1 + PUBLISHED.indexOf(message.chunk)] = { payload: message.payload };
    const anomaly = state.anomaly.active;
    const step = TirePress.STEPS[state.plc.step].name;
    node.status(anomaly
        ? { fill: "red", shape: "dot", text: "anomaly " + anomaly.kind + " " + anomaly.severity + " · " + step }
        : { fill: state.plc.fault || state.plc.hold ? "yellow" : "green", shape: "dot", text: "cycle " + state.plc.cycles + " · " + step });
    return o;
} catch (error) {
    node.error(error.message, msg);
    node.status({ fill: "red", shape: "ring", text: error.message.slice(0, 80) });
    return null;
}
`;

const readme = `Tire curing press TCP-01 simulation, model ${M.VERSION}.

Publishes SIMATIC v1 bulk payloads like an S7 connector named "${options.connector}" with connection "${options.connection}":
  metadata  ${T.metadata} (retained)
  data      ${T.read}/{${published.join(",")}} every ${options.publishEveryMs} ms
  writes    ${T.write}/{${M.chunks.filter((c) => c.writable).map((c) => c.name).join(",")}}  payload {"seq":1,"vals":[{"id":"<tag id>","val":<value>}]}

After importing: open the broker node "ie-databus" and enter a Databus user that may publish and subscribe to ie/#.
Give the flow persistent context if counters should survive a restart. One flow instance per connector name.

Anomalies: one random anomaly at a time (mean gap Cmd.Anomaly.MeanIntervalMin, default 10 min, lasting 2-7 min).
Ground truth is on the Anomaly_0 chunk; keep those tags out of detector inputs and use them to score detections.
AI Inference Server may write ${NS}.AI.* on ${T.write}/AI_0; the flow echoes them to ${T.read}/AI_0.

Rebuild with: node flow/build-flow.mjs --connector ${options.connector} --connection ${options.connection}`;

const nodes = [];
const push = (node) => (nodes.push(node), node);
push({ id: TAB, type: "tab", label: "Tire Curing Press TCP-01 - SIMULATION", disabled: false, info: readme, env: [] });
push({ id: id("readme"), type: "comment", z: TAB, name: "Read me: topics, credentials, anomalies", info: readme, x: 230, y: 40, wires: [] });
push({ id: BROKER, type: "mqtt-broker", name: "Industrial Edge Databus", broker: "ie-databus", port: "1883", clientid: `${options.connector}-sim`, autoConnect: true, usetls: false, protocolVersion: "4", keepalive: "60", cleansession: true, autoUnsubscribe: true, birthTopic: "", birthQos: "0", birthPayload: "", birthMsg: {}, closeTopic: "", closeQos: "0", closePayload: "", closeMsg: {}, willTopic: "", willQos: "0", willPayload: "", willMsg: {}, userProps: "", sessionExpiry: "" });

const inject = (key, name, topic, payload, payloadType, repeat, once, x, y) => push({
  id: id(key), type: "inject", z: TAB, name, props: [{ p: "payload" }, { p: "topic", vt: "str" }], repeat: repeat ? String(repeat) : "", crontab: "",
  once: Boolean(once), onceDelay: once || 0.1, topic, payload, payloadType, x, y, wires: [[MAIN]],
});
inject("tick", `Tick every ${options.publishEveryMs} ms`, "tcp/tick", "", "date", options.publishEveryMs / 1000, 1, 180, 120);
inject("metadata", "Publish metadata", "tcp/metadata", "", "date", 60, 0.2, 180, 170);
const commands = [
  ["start", "Start", { [`${NS}.Cmd.Start`]: true }], ["stop", "Cycle stop", { [`${NS}.Cmd.Stop`]: true }], ["reset", "Reset", { [`${NS}.Cmd.Reset`]: true }],
  ["estop-on", "E-stop press", { [`${NS}.Cmd.EStop`]: true }], ["estop-off", "E-stop release", { [`${NS}.Cmd.EStop`]: false }],
  ["anomaly-inject", `Inject anomaly 1 (edit code 1-${M.ANOMALIES.length})`, { [`${NS}.Cmd.Anomaly.Inject`]: 1 }],
  ["anomaly-clear", "End anomaly", { [`${NS}.Cmd.Anomaly.Clear`]: true }],
  ["anomaly-on", "Random anomalies on", { [`${NS}.Cmd.Anomaly.RandomEnabled`]: true }], ["anomaly-off", "Random anomalies off", { [`${NS}.Cmd.Anomaly.RandomEnabled`]: false }],
];
commands.forEach(([key, name, payload], index) => inject(`cmd-${key}`, name, "tcp/command", JSON.stringify(payload), "json", 0, 0, 180, 240 + index * 40));
push({ id: id("writes-in"), type: "mqtt in", z: TAB, name: "Writes from the Databus", topic: `${T.write}/+`, qos: "1", datatype: "auto-detect", broker: BROKER, nl: false, rap: true, rh: 0, inputs: 0, x: 170, y: 640, wires: [[MAP]] });
push({ id: MAP, type: "function", z: TAB, name: "Mark as write", func: 'msg.writeTopic = msg.topic;\nmsg.topic = "tcp/write";\nreturn msg;', outputs: 1, timeout: 0, noerr: 0, initialize: "", finalize: "", libs: [], x: 390, y: 640, wires: [[MAIN]] });

const outs = [];
const mqttOut = (key, name, topic, qos, retain, y) => { const node = push({ id: id(key), type: "mqtt out", z: TAB, name, topic, qos, retain, respTopic: "", contentType: "", userProps: "", correl: "", expiry: "", broker: BROKER, x: 900, y, wires: [] }); outs.push([node.id]); };
mqttOut("out-metadata", "Metadata", T.metadata, "1", "true", 120);
published.forEach((name, index) => mqttOut(`out-${name}`, `Data ${name}`, `${T.read}/${name}`, "0", "false", 170 + index * 50));
echoed.forEach((name, index) => mqttOut(`out-echo-${name}`, `Read-back ${name}`, `${T.read}/${name}`, "0", "false", 170 + (published.length + index) * 50));
push({ id: MAIN, type: "function", z: TAB, name: "Press model, PLC and anomaly publisher", func: main, outputs: outs.length, timeout: 0, noerr: 0, initialize: "", finalize: "", libs: [], x: 560, y: 300, wires: outs });

writeFileSync(out, JSON.stringify(nodes, null, 2) + "\n");
console.log(`wrote ${relative(ROOT, out)}: ${nodes.length} nodes, ${outs.length} outputs, data on ${T.read}/{${published.join(",")}}`);
